import { expect, test } from '@playwright/test';
import { createHash, randomUUID } from 'node:crypto';
import JSZip from '../../backend/node_modules/jszip/lib/index.js';
import { PrismaClient } from '../../backend/node_modules/@prisma/client/default.js';

test('Cotización directa → expediente: cliente canónico, ficha automática, versiones privadas y replay', async ({ page, baseURL }) => {
  expect(baseURL).toBe('http://127.0.0.1:5176');
  const target = new URL(process.env.QA_CLIENT_CASE_DATABASE_URL!);
  expect([target.hostname, target.port, target.pathname]).toEqual(['127.0.0.1', '55521', '/pravia_client_qa']);
  const db = new PrismaClient({ datasourceUrl: target.href });
  const org = '21110000-0000-4000-8000-000000000001';
  let authorization = '';
  page.on('request', request => { if (request.url().startsWith(baseURL + '/api/') && request.headers().authorization) authorization = request.headers().authorization; });
  try {
    expect(await (await page.request.get('http://127.0.0.1:3011/health')).json()).toMatchObject({ database: 'ok', database_mode: 'local', storage_mode: 'local' });
    await page.goto('/login');
    await page.getByLabel('Correo electrónico').fill('documentos.qa@pravia.test');
    await page.getByLabel('Contraseña', { exact: true }).fill(process.env.QA_LOCAL_PASSWORD!);
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
    await page.waitForURL('**/mi-dia');
    const api = async (path: string, method = 'GET', data?: unknown) => {
      const response = await page.request.fetch('/api' + path, { method, headers: { Authorization: authorization }, ...(data ? { data } : {}) });
      const result = await response.json();
      expect(response.ok(), result.code || 'canonical API request').toBe(true);
      return result;
    };
    const format = await api('/expedientes/2d49eeef-6757-4c35-84f5-9a046b47b982/ficha');
    expect(format.format.available).toBe(true);
    const client = await db.compareciente.findUniqueOrThrow({ where: { id: '21110000-0000-4000-8000-000000000003' } });
    expect(client.organization_id).toBe(org);
    const act = await db.tipoActo.findFirstOrThrow({ where: { organization_id: org, nombre: 'COMPRAVENTA SINTÉTICA QA ACT4' } });
    const before = await db.movimientoFinanciero.count({ where: { organization_id: org } });
    const quote = await api('/cotizaciones', 'POST', { formalApplicantId: client.id, operationContext: 'SINTÉTICO QA ficha automática ' + randomUUID(), confirm: true, idempotencyKey: randomUUID() });
    expect(quote.prospecto_id).toBeNull();
    await api('/cotizaciones/' + quote.id + '/actos', 'POST', { tipo_acto_id: act.id });
    let detail = await api('/cotizaciones/' + quote.id);
    await api('/cotizaciones/' + quote.id + '/presupuesto', 'PUT', { expectedUpdatedAt: detail.updated_at, concepts: [{ categoria: 'HONORARIOS', concepto: 'SINTÉTICO QA SIN VALIDEZ', importe: '1000.00' }], origin: 'MANUAL' });
    const action = async (code: string, extra = {}) => {
      detail = await api('/cotizaciones/' + quote.id);
      return api('/cotizaciones/' + quote.id + '/acciones', 'POST', { action: code, expectedVersion: detail.workflow.version, confirm: true, idempotencyKey: randomUUID(), effectiveAt: new Date().toISOString(), ...extra });
    };
    detail = await api('/cotizaciones/' + quote.id);
    if (detail.workflow.stage === 'BORRADOR') await action('COMENZAR_ELABORACION');
    await action('ENVIAR_CLIENTE', { channel: 'entrega', recipient: 'DESTINATARIO SINTÉTICO LOCAL', evidence: 'QA local; no se envió comunicación externa.', deliveryMode: 'MANUAL_CONFIRMED' });
    detail = await api('/cotizaciones/' + quote.id);
    await action('ACEPTAR', { confirmedActIds: detail.actos.map((item: any) => item.id), formalApplicantId: client.id });
    await page.goto('/cotizaciones/' + quote.id);
    await page.getByRole('button', { name: 'Convertir en expediente', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Convertir a expediente', exact: true });
    const customer = dialog.locator('dl > div').filter({ has: page.getByText('Cliente', { exact: true }) });
    await expect(customer).toContainText(client.nombre_busqueda);
    await dialog.getByLabel('Carácter del solicitante en ' + act.nombre).selectOption('NO_PARTICIPA');
    const conversion = page.waitForResponse(response => response.url().endsWith('/cotizaciones/' + quote.id + '/convertir') && response.request().method() === 'POST');
    await dialog.getByRole('button', { name: 'Convertir en expediente', exact: true }).click();
    const converted = await conversion;
    expect(converted.status()).toBe(201);
    const result = await converted.json();
    expect(result.ficha_expediente.status).toBe('GENERATED');
    await page.waitForURL('**/expedientes/' + result.id);
    const stored = await db.expediente.findUniqueOrThrow({ where: { id: result.id } });
    expect(stored.cliente_compareciente_id).toBe(client.id);
    expect(await db.expedienteCompareciente.count({ where: { expediente_id: stored.id } })).toBe(0);
    const sheets = await api('/expedientes/' + stored.id + '/ficha');
    expect(sheets.versions).toHaveLength(1);
    const first = sheets.versions[0].documento;
    const read = async (document: any) => {
      const link = await api('/expedientes/' + stored.id + '/ficha/' + document.id + '/url');
      const url = new URL(link.url, 'http://127.0.0.1:3011');
      expect(url.origin).toBe('http://127.0.0.1:3011');
      const response = await page.request.get(url.href); expect(response.status()).toBe(200);
      const bytes = await response.body(); expect(createHash('sha256').update(bytes).digest('hex')).toBe(document.checksum_sha256);
      const word = await JSZip.loadAsync(bytes);
      const xml = await word.file('word/document.xml')!.async('string');
      expect(xml).toContain(stored.numero_pravia); expect(xml).toContain(client.nombre_busqueda);
      return bytes;
    };
    const original = await read(first);
    await page.goto('/expedientes/' + stored.id + '#plantillas');
    const panel = page.getByRole('region', { name: 'Ficha de expediente', exact: true });
    await panel.getByRole('button', { name: first.nombre_original, exact: true }).click();
    const viewer = page.getByRole('dialog', { name: first.nombre_original, exact: true });
    await expect(viewer.getByText('FICHA SINTÉTICA SIN VALIDEZ', { exact: true })).toBeVisible();
    await viewer.getByRole('button', { name: 'Cerrar vista previa', exact: true }).click();
    const generated = page.waitForResponse(response => response.url().endsWith('/expedientes/' + stored.id + '/ficha') && response.request().method() === 'POST');
    await panel.getByRole('button', { name: 'Generar ficha actualizada', exact: true }).click();
    expect((await generated).status()).toBe(201);
    await page.reload();
    const current = await api('/expedientes/' + stored.id + '/ficha'); expect(current.versions).toHaveLength(2);
    const replay = await page.request.post(converted.url(), { headers: { Authorization: authorization }, data: converted.request().postDataJSON() });
    expect(replay.status()).toBe(200);
    expect(await replay.json()).toMatchObject({ id: stored.id, idempotent: true });
    expect((await api('/expedientes/' + stored.id + '/ficha')).versions).toHaveLength(2);
    expect((await read(first)).equals(original)).toBe(true);
    expect(await db.auditLog.count({ where: { organization_id: org, entidad_id: stored.id, accion: 'CASE_SHEET_GENERATED' } })).toBe(2);
    expect(await db.movimientoFinanciero.count({ where: { organization_id: org } })).toBe(before);
  } finally { await db.$disconnect(); }
});
