import { expect, test } from '@playwright/test';

test('NOV-COT: busca solicitante, permite alta contextual y reanuda la aceptación', async ({ page }, testInfo) => {
  const base = new URL(String(testInfo.project.use.baseURL || ''));
  const password = process.env.PRAVIA_E2E_PASSWORD;
  if (base.hostname !== '127.0.0.1' || base.port !== '5176' || !password) {
    throw new Error('NOV_QUOTE_ACCEPTANCE_LOCAL_QA_ONLY');
  }
  await page.goto('/login');
  await page.getByRole('textbox', { name: 'Contraseña', exact: true }).fill(password);
  const email = page.getByRole('textbox', { name: 'Correo electrónico' });
  const login = page.getByRole('button', { name: 'Iniciar sesión', exact: true });
  await email.fill('adrian.hernandez@pravia.test');
  await expect(login).toBeEnabled();
  await login.click();
  await expect(page).toHaveURL(/\/mi-dia$/);

  await page.goto('/prospectos');
  await page.getByRole('button', { name: 'Nuevo prospecto' }).click();
  await page.getByLabel('Nombre o razón social').fill(`QA NOV COT SOLICITANTE ${Date.now()}`);
  await page.getByRole('dialog').getByRole('button', { name: 'Crear prospecto' }).click();
  await page.waitForURL(/\/prospectos\/[0-9a-f-]+$/);
  const summary = page.getByRole('heading', { name: 'Resumen' }).locator('xpath=ancestor::section[1]');
  await summary.getByRole('button', { name: 'Editar datos' }).click();
  await summary.getByRole('checkbox').first().check();
  await summary.getByRole('button', { name: 'Guardar' }).click();
  await page.getByRole('button', { name: 'Comenzar integración' }).click();
  await page.getByRole('group', { name: 'Confirmar acción' }).getByRole('button', { name: 'Confirmar' }).click();
  await page.getByRole('button', { name: 'Marcar listo para cotizar' }).click();
  const readiness = page.getByRole('group', { name: 'Confirmar acción' });
  const assignee = readiness.getByRole('combobox', { name: /Quién continuará con la cotización/i });
  const director = (await assignee.locator('option').allTextContents()).find((label) => label.includes('Hernández'));
  expect(director).toBeTruthy();
  await assignee.selectOption({ label: director });
  await readiness.getByRole('button', { name: 'Confirmar' }).click();
  await page.getByRole('button', { name: 'Convertir en cotización' }).click();
  await page.getByRole('group', { name: 'Confirmar acción' }).getByRole('button', { name: 'Confirmar' }).click();
  await page.waitForURL(/\/cotizaciones\/[0-9a-f-]+$/);
  const quotePath = new URL(page.url()).pathname;

  await page.getByRole('button', { name: 'Comenzar elaboración' }).first().click();
  await page.getByRole('dialog', { name: 'Comenzar elaboración' }).getByRole('button', { name: 'Comenzar elaboración' }).click();
  await expect(page.getByText('Etapa persistida: En elaboración')).toBeVisible();
  await page.getByLabel('Concepto 1', { exact: true }).fill('Honorarios sintéticos de aceptación');
  await page.getByLabel('Importe concepto 1', { exact: true }).fill('1234.56');
  await expect(page.getByText('Hay cambios sin guardar.')).toBeVisible();
  const budgetSave = page.waitForResponse(response => response.url().endsWith(`${quotePath}/presupuesto`) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  const budgetResponse = await budgetSave;
  expect(budgetResponse.status(), await budgetResponse.text()).toBe(200);
  await expect(page.getByText('Presupuesto guardado.')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Concepto 1', { exact: true })).toHaveValue('HONORARIOS SINTÉTICOS DE ACEPTACIÓN');
  await expect(page.getByLabel('Importe concepto 1', { exact: true })).toHaveValue('1234.56');
  await page.getByRole('button', { name: 'Registrar envío al cliente' }).click();
  const delivery = page.getByRole('dialog', { name: 'Confirmar envío manual a cliente' });
  await delivery.getByLabel('Canal externo').selectOption('presencial');
  await delivery.getByLabel('Para', { exact: true }).fill('Destinatario sintético QA');
  await delivery.getByLabel('Evidencia / nota del envío realizado').fill('Entrega simulada sólo en QA local; sin contacto real.');
  await delivery.getByRole('button', { name: 'Confirmar envío manual' }).click();
  await page.getByRole('button', { name: 'Iniciar seguimiento' }).first().click();
  await page.getByRole('dialog', { name: 'Iniciar seguimiento' }).getByRole('button', { name: 'Iniciar seguimiento' }).click();
  await page.getByRole('button', { name: 'Marcar como aceptada' }).click();
  const acceptance = page.getByRole('dialog', { name: 'Registrar aceptación' });
  const effectiveAt = await acceptance.getByLabel('Fecha y hora efectiva').inputValue();
  const note = 'Observación de aceptación conservada en alta contextual QA';
  await acceptance.getByLabel('Nota opcional').fill(note);
  await acceptance.getByLabel('Buscar compareciente').fill('5F9670C5');
  const existingOption = acceptance.getByRole('option', { name: /COL67 CSF SINTETICA 5F9670C5/ });
  await expect(existingOption).toBeAttached();
  await acceptance.getByLabel('Solicitante formal').selectOption(String(await existingOption.getAttribute('value')));
  await expect(acceptance.getByLabel('Solicitante formal')).not.toHaveValue('');

  await acceptance.getByRole('link', { name: 'Agregar compareciente' }).click();
  await expect(page).toHaveURL(new RegExp(`/comparecientes/nuevo\\?fromQuote=${quotePath.split('/').at(-1)}$`));
  const createdName = `QA NOV COT NUEVO ${Date.now()}`;
  await page.getByLabel(/Nombre\(s\)/).fill(createdName);
  await page.getByRole('button', { name: 'Registrar compareciente' }).click();
  await expect(page).toHaveURL(new RegExp(`${quotePath}$`));
  const resumed = page.getByRole('dialog', { name: 'Registrar aceptación' });
  await expect(resumed.getByLabel('Fecha y hora efectiva')).toHaveValue(effectiveAt);
  await expect(resumed.getByLabel('Nota opcional')).toHaveValue(note);
  await expect(resumed.getByRole('checkbox').first()).toBeChecked();
  await expect(resumed.getByRole('option', { name: createdName })).toBeAttached();
  const selected = await resumed.getByLabel('Solicitante formal').inputValue();
  expect(selected).toMatch(/^[0-9a-f-]{36}$/);
  const action = page.waitForResponse(response => response.url().endsWith(`${quotePath}/acciones`) && response.request().method() === 'POST');
  await resumed.getByRole('button', { name: 'Confirmar aceptación' }).click();
  const accepted = await action;
  expect(accepted.status(), await accepted.text()).toBe(201);
  expect(accepted.request().postDataJSON()).toMatchObject({ action: 'ACEPTAR', reason: note, formalApplicantId: selected });
  await expect(page.getByRole('button', { name: 'Convertir en expediente', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Convertir en expediente', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Convertir en expediente', exact: true }).click();
  const conversion = page.getByRole('dialog', { name: 'Convertir a expediente' });
  const responsible = conversion.getByRole('combobox', { name: 'Responsable del expediente' });
  await expect(responsible).toBeEnabled();
  const javier = (await responsible.locator('option').allTextContents()).find((label) => label.includes('Javier Tapia'));
  expect(javier).toBeTruthy();
  await responsible.selectOption({ label: javier });
  const selectedResponsibleId = await responsible.inputValue();
  const formalRole = conversion.getByRole('combobox', { name: /Carácter del solicitante en/i });
  await formalRole.selectOption({ index: 2 });
  const convertResponse = page.waitForResponse((response) => response.url().endsWith(`${quotePath}/convertir`) && response.request().method() === 'POST');
  await conversion.getByRole('button', { name: 'Convertir en expediente' }).click();
  const created = await convertResponse;
  expect(created.status(), await created.text()).toBe(201);
  const expediente = await created.json();
  expect(expediente.abogado_id).toBe(selectedResponsibleId);
  const replay = await page.request.post(created.url(), {
    headers: { authorization: created.request().headers().authorization },
    data: created.request().postDataJSON(),
  });
  expect(replay.status(), await replay.text()).toBe(200);
  expect(await replay.json()).toMatchObject({ id: expediente.id, idempotent: true });
  await expect(page).toHaveURL(new RegExp(`/expedientes/${expediente.id}$`));
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Número de expediente' })).toHaveValue(expediente.numero_pravia);
  await expect(page.getByRole('combobox', { name: 'Abogado responsable' })).toHaveValue(selectedResponsibleId);
  await page.goto(quotePath);
  await expect(page.getByRole('link', { name: 'Ir al expediente' })).toHaveAttribute('href', `/expedientes/${expediente.id}`);
});
